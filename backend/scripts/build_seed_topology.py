"""Generate the waterplant seed from plants/waterplant.

Writes
  supabase/seed/01_plant_release.sql  one release (all plant tables, in foreign-key order)
  supabase/seed/02_plant_memory.sql   the plant_memory blocks the AI is given on incident open
  docs/TOPOLOGY.md                    the same blocks for people

Run from backend/:  uv run python scripts/build_seed_topology.py
Load 01 and 02 into a database that already has the migrations applied."""
from __future__ import annotations

import json
import math
import sys
import uuid
from pathlib import Path
from typing import Any

BACKEND = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND))

from app.plant.loader import content_hash, load_pack  # noqa: E402
from app.plant.memory import MemoryBlock, build_memory  # noqa: E402
from app.plant.models import PlantPack  # noqa: E402
from app.plant.rows import to_rows  # noqa: E402

REPO = BACKEND.parent
PACK_DIR = REPO / "plants" / "waterplant"
SEED_DIR = REPO / "supabase" / "seed"
DOC_PATH = REPO / "docs" / "TOPOLOGY.md"

# Parents before children. plant_assets.parent_asset_id is a deferrable self-reference.
TABLE_ORDER = [
    "plant_releases", "plant_assets", "plant_ports", "plant_edges",
    "plant_routes", "data_sources", "instruments",
]
TEXT_ARRAY_COLUMNS = {("plant_routes", "edge_ids"), ("instruments", "attach_refs")}
RELEASE_NAMESPACE = uuid.uuid5(uuid.NAMESPACE_URL, "https://faultglass.local/plant-release")
HEADER = "-- GENERATED by backend/scripts/build_seed_topology.py from plants/waterplant. Do not edit by hand.\n"


def quote(text: str) -> str:
    """SQL string literal (standard_conforming_strings is on, so only quotes need doubling)."""
    if "\x00" in text:
        raise ValueError("NUL byte in text value")
    return "'" + text.replace("'", "''") + "'"


def literal(table: str, column: str, value: Any) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, (int, float)):
        if isinstance(value, float) and not math.isfinite(value):
            raise ValueError(f"{table}.{column}: non-finite number")
        return repr(value)
    if (table, column) in TEXT_ARRAY_COLUMNS:
        if not all(isinstance(v, str) for v in value):
            raise ValueError(f"{table}.{column}: text[] needs strings")
        if not value:
            return "'{}'::text[]"
        return "ARRAY[" + ", ".join(quote(v) for v in value) + "]::text[]"
    if isinstance(value, str):
        return quote(value)
    if isinstance(value, (dict, list)):
        return quote(json.dumps(value, ensure_ascii=False, sort_keys=True)) + "::jsonb"
    raise TypeError(f"{table}.{column}: unsupported value {type(value).__name__}")


def insert(table: str, rows: list[dict[str, Any]]) -> str:
    if not rows:
        return ""
    cols = list(rows[0])
    if any(list(r) != cols for r in rows):
        raise ValueError(f"{table}: rows have different columns")
    body = ",\n".join("  (" + ", ".join(literal(table, c, r[c]) for c in cols) + ")" for r in rows)
    return f"INSERT INTO {table} ({', '.join(cols)}) VALUES\n{body};\n"


def release_sql(pack: PlantPack, release_id: str, digest: str) -> str:
    rows = to_rows(pack, release_id, digest)
    parts = [
        HEADER,
        f"-- Release {release_id} (plant {pack.manifest.id} {pack.manifest.version}, sha256 {digest}).",
        "-- Empty database only: re-running fails on the unique (plant_id, content_hash) key.",
        "BEGIN;",
    ]
    parts += [insert(t, rows[t]) for t in TABLE_ORDER]
    parts.append("COMMIT;")
    return "\n".join(p for p in parts if p) + "\n"


def memory_sql(pack: PlantPack, blocks: list[MemoryBlock]) -> str:
    values = ",\n".join(
        "  (" + ", ".join(quote(x) for x in (pack.manifest.id, b.kind, b.title, b.body_md,
                                             pack.manifest.data_origin)) + ")"
        for b in blocks
    )
    return "\n".join([
        HEADER.rstrip(),
        "-- Plant memory injected when an incident opens. Re-running updates the same rows.",
        "BEGIN;",
        "INSERT INTO plant_memory (plant_id, kind, title, body_md, data_origin) VALUES",
        values,
        "ON CONFLICT (plant_id, kind) DO UPDATE SET",
        "  title = EXCLUDED.title, body_md = EXCLUDED.body_md, data_origin = EXCLUDED.data_origin;",
        "COMMIT;",
        "",
    ])


def topology_doc(pack: PlantPack, blocks: list[MemoryBlock]) -> str:
    out = [
        f"# {pack.manifest.name}: topology and plant memory",
        "",
        "Generated by `backend/scripts/build_seed_topology.py` from `plants/waterplant`. These are the",
        "blocks the AI is given as plant memory when an incident opens. Change the pack, then regenerate.",
        "",
    ]
    for b in blocks:
        out += [f"# {b.title}", "", b.body_md.rstrip(), ""]
    return "\n".join(out)


def main() -> None:
    pack = load_pack(PACK_DIR)
    digest = content_hash(pack)
    release_id = str(uuid.uuid5(RELEASE_NAMESPACE, f"{pack.manifest.id}:{digest}"))
    blocks = build_memory(pack)

    SEED_DIR.mkdir(parents=True, exist_ok=True)
    (SEED_DIR / "01_plant_release.sql").write_text(release_sql(pack, release_id, digest), encoding="utf-8")
    (SEED_DIR / "02_plant_memory.sql").write_text(memory_sql(pack, blocks), encoding="utf-8")
    DOC_PATH.write_text(topology_doc(pack, blocks), encoding="utf-8")

    rows = to_rows(pack, release_id, digest)
    counts = ", ".join(f"{t} {len(rows[t])}" for t in TABLE_ORDER)
    print(f"release {release_id}  sha256:{digest[:12]}")
    print(f"rows: {counts}")
    print(f"plant_memory: {len(blocks)} blocks ({', '.join(f'{b.kind} {len(b.body_md)}' for b in blocks)} chars)")


if __name__ == "__main__":
    main()
