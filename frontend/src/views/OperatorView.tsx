import React from 'react';
import { ApiUnreachable } from '../components/common/ApiUnreachable';
import { ConnectionBanner } from '../components/common/ConnectionBanner';
import { Pill } from '../components/common/Pill';
import { FlagsPanel } from '../components/operator/FlagsPanel';
import { IncidentWorkbench } from '../components/operator/IncidentWorkbench';
import { RunControls, RunPanel } from '../components/operator/RunPanel';
import { SignalsPanel } from '../components/operator/SignalsPanel';
import { usePlant } from '../state/PlantContext';
import type { View } from '../state/route';
import '../styles/operator.css';

export const OperatorView: React.FC<{ onNavigate: (view: View) => void }> = ({ onNavigate }) => {
  const { plant } = usePlant();
  if (!plant) return <ApiUnreachable />;

  return (
    <div className="operator">
      <ConnectionBanner />
      <div className="page-head">
        <div>
          <h1>Operator console</h1>
          <p className="muted">Live signals, the watcher's flags and the investigation.</p>
        </div>
        <RunControls />
      </div>

      <div className="section-head">
        <h2>Live signals</h2>
        {plant.simulation && <Pill tone="warning">Simulated</Pill>}
        <span className="muted small">
          {plant.simulation ? 'Generated by the plant simulator, not read from a real controller.' : 'Read from the plant controller.'}
        </span>
      </div>

      <div className="operator-top">
        <SignalsPanel />
        <aside className="operator-side">
          <FlagsPanel />
          <RunPanel />
        </aside>
      </div>

      <IncidentWorkbench onOpenField={() => onNavigate('field')} />
    </div>
  );
};
